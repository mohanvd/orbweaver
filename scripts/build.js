/**
 * Bundles src/ into a single readable file that can be pasted into the console.
 * The output is deliberately not minified: people should be able to read what they run.
 */

import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const pkg = JSON.parse(await readFile(new URL("package.json", root), "utf8"));

const banner = `/*!
 * orbweaver v${pkg.version}
 * ${pkg.repository.url.replace(/^git\+|\.git$/g, "")}
 *
 * Automating quests is against Discord's rules and Discord enforces it.
 * Read the README before running this on an account you care about.
 *
 * Generated from src/. Do not edit this file by hand.
 */`;

await build({
	entryPoints: [fileURLToPath(new URL("src/index.js", root))],
	outfile: fileURLToPath(new URL("dist/orbweaver.js", root)),
	bundle: true,
	format: "iife",
	target: "es2022",
	minify: false,
	legalComments: "none",
	banner: { js: banner },
	logLevel: "info",
});
